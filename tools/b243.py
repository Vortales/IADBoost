# -*- coding: utf-8 -*-
from pack import sec, pair, bill, OUT
from make_acts import build

UK = "Уголовный Кодекс штата Сан-Андреас.json"
t = sec(UK, 243)
tail = "ч.3" + t.split("ч.3", 1)[1].rstrip() + "\n" + sec(UK, 244).strip()
r1 = pair(tail, "5 лет лет лишения свободы", "5 лет лишения свободы")

line = [l for l in sec(UK, 173).split("\n") if "в соответствие с" in l][0]
r2 = pair(line, "в соответствие с законодательством", "в соответствии с законодательством")

line3 = [l for l in sec(UK, 245).split("\n") if "совокупность всех фактом" in l][0]
r3 = pair("Статья 15.7. Комментарий\n" + line3, "совокупность всех фактом", "совокупность всех факторов")

b = bill(243,
 "ACT. 243 — Технические исправления в Уголовный кодекс.docx",
 "о внесении технических исправлений в Уголовный кодекс штата San-Andreas",
 "В Уголовный кодекс штата San-Andreas вносятся три технических исправления. В части 3 статьи 15.6 (халатность при повторности) в санкции дважды употреблено слово «лет» — «5 лет лет лишения свободы»; повтор устраняется, срок наказания не изменяется. В статье 9.1 (незаконное проникновение на охраняемый объект) предлог употреблён в форме «в соответствие с», тогда как в законодательстве используется форма «в соответствии с». В комментарии к части 1 статьи 15.7 слово «фактом» заменяется на «факторов» — по смыслу речь идёт о совокупности факторов. Все исправления носят редакционный характер.",
 "SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Уголовный кодекс штата San-Andreas",
 [r1, r2, r3])
build(b, OUT)

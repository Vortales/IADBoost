def pair(src, edits):
    """edits — список (old, new) в порядке следования в тексте.

    Слева old подсвечивается красным, справа new — зелёным. Если new пуст,
    фрагмент считается удалённым.
    """
    pos, L, R = 0, [], []
    for old, new in edits:
        i = src.find(old, pos)
        if i < 0:
            raise ValueError("не найдено: %r" % old[:70])
        L.append(src[pos:i])
        R.append(src[pos:i])
        L.append("[[R]]%s[[/R]]" % old)
        if new:
            R.append("[[G]]%s[[/G]]" % new)
        pos = i + len(old)
    L.append(src[pos:])
    R.append(src[pos:])
    return "".join(L), "".join(R)



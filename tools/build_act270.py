def cut(text, first, last=None):
    i = text.find(first)
    if i < 0:
        raise ValueError("не найдено: %r" % first[:60])
    j = len(text) if last is None else text.find(last, i)
    return text[i:j].rstrip()


def rep(text, pairs):
    """Пара (old, new): слева old помечается красным, справа new — зелёным."""
    left, right = text, text
    for old, new in pairs:
        for holder, mark, frag in ((left, "R", old), (right, "G", new)):
            if holder.count(old) != 1:
                raise ValueError("фрагмент не уникален (%d): %r"
                                 % (holder.count(old), old[:70]))
        left = left.replace(old, "[[R]]%s[[/R]]" % old)
        right = right.replace(old, "[[G]]%s[[/G]]" % new)
    return left, right



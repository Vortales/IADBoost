def art(n):
    """Статья вместе с наказанием: наказание в базе лежит отдельной записью."""
    head = SEC[n].rstrip()
    assert head.endswith("Наказание:"), head[-40:]
    return head[:-len("Наказание:")] + "Наказание:\n" + SEC[n + 1].strip()


def pair(src, edits):
    """edits — список ("R", old, new) либо ("I", anchor, text).

    "R" — замена: слева old красным, справа new зелёным.
    "I" — вставка после anchor: слева без изменений, справа text зелёным.
    """
    pos, L, R = 0, [], []
    for kind, old, new in edits:
        i = src.find(old, pos)
        if i < 0:
            raise ValueError("не найдено: %r" % old[:70])
        cut = i + len(old)
        L.append(src[pos:cut])
        R.append(src[pos:cut])
        if kind == "R":
            L[-1] = src[pos:i] + "[[R]]%s[[/R]]" % old
            if new:
                R[-1] = src[pos:i] + "[[G]]%s[[/G]]" % new
        elif kind == "I":
            if new:
                R[-1] = src[pos:cut] + "[[G]]%s[[/G]]" % new
        else:
            raise ValueError(kind)
        pos = cut
    L.append(src[pos:])
    R.append(src[pos:])
    return "".join(L), "".join(R)



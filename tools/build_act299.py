"""ACT. 299: неприкосновенность лично отстранённого сенатора.

Действующая редакция берётся из законодательной базы. Порядок и срок личного
отстранения уточняются связанным законопроектом ACT. 300.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from billkit import load  # noqa: E402
from make_acts import build  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Законопроекты",
                   "Законопроекты 299 (неприкосновенность сенатора)")
IMM_FILE = "Закон Об обеспечении неприкосновенности государственных служащих штата Сан-Андреас"
IMM_NAME = "Закон «Об обеспечении неприкосновенности государственных служащих штата San-Andreas»"
SEN_GEN = "Конституционного закона «О Сенате штата Сан-Андреас»"

article_6 = load(IMM_FILE)[15]
assert article_6.startswith("Статья 6.\n")
assert "ч. 1 Действие статуса неприкосновенности приостанавливается в случаях:" in article_6
assert not re.search(r"(?m)^г\)", article_6), "Пункт «г» уже существует в статье 6"

new_point = (
    "г) на время личного отстранения сенатора от участия в заседании Сената штата "
    "Сан-Андреас по решению Спикера Сената штата Сан-Андреас за нарушение сенатором "
    "регламента проведения заседания и (или) правопорядка в ходе заседания в порядке, "
    "предусмотренном пунктом «л» части 4 статьи 3 [[B]]" + SEN_GEN + "[[/B]]. "
    "Приостановление по настоящему пункту прекращается с прекращением отстранения, "
    "но не позднее окончания заседания, от участия в котором сенатор отстранён."
)
heading = "[[B]]" + IMM_NAME + "[[/B]]\nСтатья 6, часть 1, пункт «г»\n"

bill = {
    "num": "299",
    "date": "NOVEMBER 13, 2026",
    "file": "ACT.299.Закон о неприкосновенности.docx",
    "subtitle": "о внесении изменений в [[B]]" + IMM_NAME + "[[/B]]",
    "section1": (
        "Законопроект устанавливает приостановление статуса неприкосновенности сенатора "
        "на время его личного отстранения от участия в заседании Сената за нарушение "
        "регламента проведения заседания и (или) правопорядка."
    ),
    "section2": "SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В [[B]]" + IMM_NAME + "[[/B]]",
    "rows": [
        (heading + "В действующей редакции отсутствует.",
         heading + "[[G]]" + new_point + "[[/G]]"),
    ],
}

os.makedirs(OUT, exist_ok=True)
build(bill, OUT)

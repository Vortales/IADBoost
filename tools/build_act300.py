def absent_row(locator, proposed):
    heading = "[[B]]" + PC + "[[/B]]\n" + locator + "\n"
    return (
        heading + "В действующей редакции отсутствует.",
        heading + "[[G]]" + proposed + "[[/G]]",
    )


def validate_source():
    source = load(PC)
    assert not any(
        re.match(r"^\s*Статья\s+8\.1(?:\D|$)", text)
        for text in source.values()
    ), "Статья 8.1 уже есть в действующей редакции"
    section20 = source[33]
    assert section20.startswith("Статья 20\n"), "Проверьте нумерацию статьи 20"
    assert "ч. 2.\n" in section20, "Проверьте часть 2 статьи 20"
    part2 = section20.split("ч. 2.\n", 1)[1]
    assert not re.search(r"^\s*ж\)", part2, flags=re.MULTILINE), (
        "Пункт «ж» части 2 статьи 20 уже есть в действующей редакции"
    )



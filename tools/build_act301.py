def one_line(text, prefix):
    matches = [line for line in text.splitlines() if line.startswith(prefix)]
    if len(matches) != 1:
        raise ValueError(f"Не найден единственный исходный фрагмент: {prefix!r}")
    return matches[0]


def absent_row(locator, proposed, act=PC):
    heading = f"[[B]]{act}[[/B]]\n{locator}\n"
    return (heading + "В действующей редакции отсутствует.",
            heading + "[[G]]" + proposed + "[[/G]]")


def prepare_rows():
    source = load(PC)
    if any(re.match(r"^\s*Статья\s+17\.3(?:\D|$)", text) for text in source.values()):
        raise ValueError("Статья 17.3 уже есть в действующей редакции")
    p17, p22, p23 = source[25], source[35], source[36]
    if not p17.startswith("Статья 17\n") or not p22.startswith("Статья 22\n") or not p23.startswith("Статья 23\n"):
        raise ValueError("Изменились номера записей Процессуального кодекса")
    law8 = load(AD_SOURCE)[17]
    if not law8.startswith("Статья 8. Клиент\n"):
        raise ValueError("Изменилась запись статьи 8 Закона об адвокатуре")
    app4 = load(APP_SOURCE)[7]
    if not app4.startswith("Статья 4\n"):
        raise ValueError("Изменилась запись статьи 4 Приложения № 1")
    if re.search(r"^\s*Примечание\s+2\.1(?:\s|:|$)", app4, re.MULTILINE):
        raise ValueError("Примечание 2.1 к статье 4 Приложения № 1 уже существует")
    original_note2 = one_line(app4, "Примечание 2: Государственные и частные адвокаты")
    if 'только в рамках вызова через телефон, если ранее с адвокатом был заключен договор, или через приложение "Адвокаты"' not in original_note2:
        raise ValueError("Изменилось примечание 2 к статье 4 Приложения № 1")
    state = one_line(p17, "В случае если задержанный требует государственного адвоката,")
    private = one_line(p17, "В случае, если задержанный требует самостоятельно вызвать частного адвоката,")

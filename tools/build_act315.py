        """Одна адресная, непересекающаяся правка с буквальной левой колонкой."""
        text = clean(documents[source][section])
        old = clean(old)
        if not old or text.count(old) != 1:
            raise ValueError(f"Не найден или не уникален фрагмент {locator}: {old[:140]!r}")
        start = text.index(old)
        end = start + len(old)
        for a, b, where in spans.setdefault((source, section), []):
            if start < b and a < end:
                raise ValueError(f"Пересекаются {where} и {locator}")
        spans[(source, section)].append((start, end, locator))
        head = f"{bold(titles[source])}\n{locator}\n"
        shown = instruction if instruction is not None else new

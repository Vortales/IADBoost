    def replace(source, section, locator, old, new, instruction=None):
        text, old = clean(documents[source][section]), clean(old)
        if not old or text.count(old) != 1:
            raise ValueError(f"Не найден или не уникален фрагмент {locator}: {old[:120]!r}")
        start, end = text.index(old), text.index(old) + len(old)
        for a, b, where in spans.setdefault((source, section), []):
            if start < b and a < end:
                raise ValueError(f"Пересекаются {where} и {locator}")
        spans[(source, section)].append((start, end, locator))
        head = f"{bold(titles[source])}\n{locator}\n"
        old_shown = old.replace("Приложением № 1 к Уголовному кодексу штата San-Andreas",
                                bold("Приложением № 1 к Уголовному кодексу штата San-Andreas"))
        shown = instruction if instruction is not None else new
        rows.append((head + "[[R]]" + old_shown + "[[/R]]",
                     head + "[[G]]" + shown + "[[/G]]"))
        patches.append(Patch(source, section, locator, old, plain(new)))

    def add(source, section, locator, marker, new):
        if marker in clean(documents[source][section]):
            raise ValueError(f"Норма уже существует: {locator}")
        head = f"{bold(titles[source])}\n{locator}\n"
        rows.append((head + "В действующей редакции отсутствует.",
                     head + "[[G]]" + new + "[[/G]]"))
        patches.append(Patch(source, section, locator, "", plain(new)))


def apply_patches(patches, documents):
    """Восстанавливает конечные редакции для проверки всех адресных изменений."""
    result = {(name, n): clean(text) for name, sections in documents.items() for n, text in sections.items()}
    for p in patches:
        key = (p.source, p.section)
        if p.old:
            if result[key].count(p.old) != 1:
                raise ValueError(f"Не удалось применить {p.locator}")
            result[key] = result[key].replace(p.old, p.new, 1)
        else:
            result[key] = result[key].rstrip() + "\n" + p.new
    return result


def polish_pagination(path):
    """Неразрывные сравнения, безопасные поля таблицы и однострочный колонтитул."""
    doc = Document(path)
    section = doc.sections[0]
    table = doc.tables[0]
    # У образца таблица выходит к самому краю листа. Оставляем по 0,3 дюйма
    # для печати, сохраняя две равные колонки и фиксированную ширину.
    outer_margin = 432  # twips (0,3 дюйма)
    half = (section.page_width.twips - 2 * outer_margin) // 2
    for name, width in (("w:tblW", 2 * half), ("w:tblInd", outer_margin - section.left_margin.twips)):
        element = table._tbl.tblPr.find(qn(name))
        if element is None:
            raise ValueError(f"Не найден элемент таблицы {name}")
        element.set(qn("w:w"), str(width))
        element.set(qn("w:type"), "dxa")
    for column in table._tbl.tblGrid.gridCol_lst:
        column.set(qn("w:w"), str(half))
    for row in table.rows:
        for cell in row.cells:
            cell.width = Twips(half)
    for row in table.rows[1:]:
        for cell in row.cells:
            # Неразрывность строки уже обеспечивает связь заголовка с текстом;
            # keep-next здесь связывал и соседние строки в некоторых просмотрщиках.
            for paragraph in cell.paragraphs[:2]:
                paragraph.paragraph_format.keep_with_next = False
    # Пустой абзац после последней таблицы образца способен создать пустую страницу.
    trailing = table._tbl.getnext()
    if (trailing is not None and trailing.tag == qn("w:p") and not "".join(trailing.itertext())
            and trailing.getnext() is not None and trailing.getnext().tag == qn("w:sectPr")):
        trailing.getparent().remove(trailing)
    footer = section.footer.paragraphs[1]
    tab_runs = [run for run in footer.runs if run.text == "\t"]
    if len(tab_runs) < 2 or "Attest: __________________" not in footer.text:
        raise ValueError("Неожиданный колонтитул образца")
    for run in tab_runs[-2:]:
        run.text = ""
    doc.save(path)


def main():
    bill, patches, documents = specs()

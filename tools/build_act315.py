TOKEN = re.compile(r"\[\[/?(?:R|G|B)\]\]")


def plain(text):
    return TOKEN.sub("", text)


def bold(text):
    return f"[[B]]{text}[[/B]]"


@dataclass(frozen=True)
class Patch:
    source: str
    section: int
    locator: str
    old: str
    new: str



        "Если при задержании установлено, что задержанный - государственный служащий, "
        "сотрудник Weazel News или частный адвокат с действующей лицензией, инициатор задержания "
        "обязан вызвать начальство задержанного (для частного адвоката - Главу Коллегии адвокатов "
        "или его заместителя) и сотрудника Офиса Генерального прокурора штата Сан-Андреас."

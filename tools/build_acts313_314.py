def unique(section, fragment):
    """Возвращает единственный исходный фрагмент, пригодный для сравнения."""
    section = clean(section)
    fragment = clean(fragment)
    if section.count(fragment) != 1:
        raise ValueError(f"Фрагмент не найден или не уникален: {fragment!r}")
    return fragment



def build():
    t = json.load(open(SRC, encoding="utf-8"))["posts"][0]["text"].replace("\u200b", "")
    body = "\n".join(l.rstrip() for l in t.split("\n"))

    marks = []
    for tag, start, end, note in MARKS:
        i = body.find(start)
        if i < 0:
            raise SystemExit(f"[{tag}] начало не найдено: {start[:60]!r}")
        if body.count(start) > 1:
            raise SystemExit(f"[{tag}] начало встречается {body.count(start)} раз")
        if end:
            j = body.find(end, i)
            if j < 0:
                raise SystemExit(f"[{tag}] конец не найден: {end[:60]!r}")
            j += len(end)
        else:
            j = i + len(start)
        marks.append((i, j, tag, note))

    marks.sort()
    for a, b in zip(marks, marks[1:]):
        if a[1] > b[0]:
            raise SystemExit(f"пересечение {a[2]} и {b[2]}")

    out, pos = [], 0
    for i, j, tag, note in marks:
        out.append(body[pos:i])
        frag = body[i:j].replace("\n", " ")
        out.append("[[" + frag + "]]")
        out.append("{{" + note + "}}")
        pos = j
    out.append(body[pos:])
    body = "".join(out)

    res = []
    for line in body.split("\n"):
        s = line.strip()
        if not s:
            res.append("")
            continue
        if re.match(r"^(ГЛАВА|Глава)\s+[IVX]+\.", s):
            res.append("\n## " + s)
            continue
        if re.match(r"^Статья\s+\d+(\.\d+)?\.?$", s):
            res.append("\n### " + s)
            continue
        res.append(s)
        res.append("")
    md = "\n".join(res)
    md = re.sub(r"\n{3,}", "\n\n", md)
    open(OUT, "w", encoding="utf-8").write(md.strip() + "\n")
    print("меток:", len(marks), "| символов:", len(md))


if __name__ == "__main__":
    build()

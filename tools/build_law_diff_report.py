def para(doc, text, size=12, bold=False, italic=False, align="justify",
         before=0, after=6, indent=1.25, color=DARK, keep=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = {"justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
                    "left": WD_ALIGN_PARAGRAPH.LEFT,
                    "center": WD_ALIGN_PARAGRAPH.CENTER}[align]
    pf.first_line_indent = Cm(indent)
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = 1.15
    pf.keep_with_next = keep
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    r.font.name = BODY
    r.font.size = Pt(size)
    r.font.color.rgb = color
    r._element.rPr.rFonts.set(qn("w:eastAsia"), BODY)
    return p


def heading(doc, text, size=13, before=14, after=6):
    return para(doc, text, size=size, bold=True, align="left", before=before,
                after=after, indent=0, keep=True)


def borders(cell):
    tcPr = cell._tc.get_or_add_tcPr()
    b = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "9A9A9A")
        b.append(el)
    tcPr.append(b)


def shade(cell, color="EDEDED"):
    tcPr = cell._tc.get_or_add_tcPr()
    s = OxmlElement("w:shd")
    s.set(qn("w:val"), "clear")
    s.set(qn("w:color"), "auto")
    s.set(qn("w:fill"), color)
    tcPr.append(s)


def put(cell, text, bold=False, size=10, color=DARK, align="left"):
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = {"left": WD_ALIGN_PARAGRAPH.LEFT,
                   "center": WD_ALIGN_PARAGRAPH.CENTER}[align]
    pf = p.paragraph_format
    pf.space_before = Pt(1)
    pf.space_after = Pt(1)
    pf.line_spacing = 1.0
    r = p.add_run(text)
    r.bold = bold
    r.font.name = BODY
    r.font.size = Pt(size)
    r.font.color.rgb = color
    r._element.rPr.rFonts.set(qn("w:eastAsia"), BODY)
    borders(cell)


def table(doc, head, rows, widths):
    t = doc.add_table(rows=1, cols=len(head))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    t._tbl.tblPr.append(layout)
    for i, h in enumerate(head):
        put(t.rows[0].cells[i], h, bold=True, align="center")
        shade(t.rows[0].cells[i])
        t.rows[0].cells[i].width = Cm(widths[i])
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            put(cells[i], v)
            cells[i].width = Cm(widths[i])
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t



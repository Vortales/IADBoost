def with_text(proto, text):
    """Копия абзаца-образца с заменой текста (вёрстка сохраняется)."""
    el = copy.deepcopy(proto)
    runs = el.findall(qn("w:r"))
    keep = None
    for r in runs:
        t = r.find(qn("w:t"))
        if t is not None and keep is None and (t.text or "").strip():
            keep = r
        else:
            el.remove(r)
    if keep is None:
        raise ValueError("в абзаце-образце нет текстового прогона")
    for child in list(keep):
        if child.tag not in (qn("w:rPr"), qn("w:t")):
            keep.remove(child)          # разрывы строки, рисунки и т.п.
    t = keep.find(qn("w:t"))
    t.text = text
    t.set(qn("xml:space"), "preserve")
    return el


def main():
    doc = Document(SRC)
    ps = doc.paragraphs
    proto_body, proto_h1 = ps[5]._p, ps[12]._p
    proto_item = ps[14]._p
    proto_sign = [ps[24]._p, ps[25]._p, ps[26]._p]

    # подзаголовок
    old = ps[2]._p
    new = with_text(old, SUBTITLE)
    old.addprevious(new)
    old.getparent().remove(old)

    body_el = doc.element.body
    sect = body_el.find(qn("w:sectPr"))

    # удалить всё после «Уважаемые сенаторы!» (индекс 4)
    for p in ps[5:]:
        p._p.getparent().remove(p._p)

    seq = []
    seq += [with_text(proto_body, t) for t in BODY]
    seq.append(with_text(proto_h1, "ПРОШУ СЕНАТ"))
    seq += [with_text(proto_item, t) for t in ITEMS]
    seq += [with_text(proto_body, t) for t in AFTER]
    seq.append(with_text(proto_h1, "ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ"))
    seq += [with_text(proto_body, t) for t in FINAL]
    seq += [with_text(proto_sign[0], SIGN[0]),
            with_text(proto_sign[1], SIGN[1]),
            with_text(proto_sign[2], SIGN[2])]

    for el in seq:
        sect.addprevious(el)

    # в колонтитуле оставался автограф постороннего лица — убрать рисунок
    for part in (doc.sections[0].footer,):
        for p in part.paragraphs:
            for r in list(p.runs):
                if r._r.find(qn("w:drawing")) is not None or r._r.find(qn("w:pict")) is not None:
                    if r._r.find(qn("w:t")) is None:
                        r._r.getparent().remove(r._r)

    doc.save(OUT)
    print("OK", OUT)


if __name__ == "__main__":
    main()

# -*- coding: utf-8 -*-
"""Сборка разбора коллизий КЗ «О Сенате»: полный текст + красные пометки."""
import glob, json, re

SRC = "Законодательная база/Конституционный закон «О Сенате штата Сан-Андреас».json"
OUT = "Аналитика/Коллизии — КЗ О Сенате/_body.md"

MARKS = [
 ("A1", "Сенат состоит из сенаторов", "органов исполнительной власти.",
  "Не работает: Конституция ст. 56 ч. 2 — по два представителя от каждого органа исполнительной власти; ч. 3 — один представитель от каждой зарегистрированной партии. Ни квоты, ни партий здесь нет, хотя Закон «О политических партиях» ст. 21 ссылается на этот закон именно за числом."),

 ("A2", "Сенат штата Сан-Андреас избирает из своего состава Председателя", "и его заместителя.",
  "Не работает: должности «Председатель штата Сан-Андреас» не существует. Конституция ст. 56 ч. 1, 57 ч. 2, 60 ч. 1 называют главу Сената Спикером; этого наименования закон не употребляет ни разу."),

 ("A3", "Председатель Сената штата Сан-Андреас при избрании на свой пост", "утрачивает полномочия сенатора.",
  "Внутреннее противоречие: председатель избирается «из своего состава» (ст. 2 ч. 2), но с избранием из состава выбывает — возглавляет орган, членом которого не является. Конституция ст. 61 — постановления принимают сенаторы; голос председателя не учтён нигде."),

 ("A4", "вправе отстранить организацию или отдельных сенаторов", "до момента уплаты штрафа.",
  "Не работает: Конституция ст. 56 ч. 3 — в Сенат входит представитель от каждой зарегистрированной партии. Отстранение партии лишает её представительства, то есть меняет состав Сената решением одного лица."),

 ("A5", "При отсутствии избранных", "нового Председателя Сената штата Сан-Андреас.",
  "Не работает: Конституция ст. 20 ч. 1 — органы законодательной и исполнительной власти самостоятельны; ст. 55 ч. 2 — Сенат подчиняется только законодательству. Заседание законодательного органа назначает и ведёт Вице-губернатор — должностное лицо исполнительной власти."),

 ("A6", "Все решения Сената штата Сан-Андреас, за исключением законопроектов", "вступают в силу немедленно",
  "Не работает для нормативных постановлений (ст. 7 ч. 1 «в»): Конституция ст. 74 ч. 4 — нормативные акты, затрагивающие права и обязанности граждан, не применяются, пока не опубликованы официально."),

 ("A7", "Заседание считается открытым", "проголосовали «за».",
  "Внутреннее противоречие: по ст. 9 ч. 1 заседание открывается решением Сената и правомочно при половине действующих сенаторов; здесь для открытия достаточно половины присутствующих, то есть примерно четверти состава."),

 ("A8", "квалифицированным большинством голосов от общего числа сенаторов", "",
  "Пробел: «квалифицированное большинство» в законодательстве штата не определено — ни здесь, ни в Конституции (ст. 61 говорит только о простом большинстве). Неясно, две трети это или три четверти."),
]


def build():
    t = json.load(open(SRC, encoding="utf-8"))["posts"][0]["text"].replace("\u200b", "")
    body = "\n".join(l.rstrip() for l in t.split("\n"))

    marks = []
    for tag, start, end, note in MARKS:
        i = body.find(start)
        if i < 0:
            raise SystemExit(f"[{tag}] начало не найдено: {start[:60]!r}")
        if body.count(start) > 1:
            raise SystemExit(f"[{tag}] начало встречается {body.count(start)} раз")
        if end:
            j = body.find(end, i)
            if j < 0:
                raise SystemExit(f"[{tag}] конец не найден: {end[:60]!r}")
            j += len(end)
        else:
            j = i + len(start)
        marks.append((i, j, tag, note))

    marks.sort()
    for a, b in zip(marks, marks[1:]):
        if a[1] > b[0]:
            raise SystemExit(f"пересечение {a[2]} и {b[2]}")

    out, pos = [], 0
    for i, j, tag, note in marks:
        out.append(body[pos:i])
        out.append("[[" + body[i:j] + "]]")
        out.append("{{" + note + "}}")
        pos = j
    out.append(body[pos:])
    body = "".join(out)

    res = []
    for line in body.split("\n"):
        s = line.strip()
        if not s:
            res.append("")
            continue
        if re.match(r"^(ГЛАВА|Глава)\s+[IVX]+\.", s):
            res.append("\n## " + s)
            continue
        if re.match(r"^Статья\s+\d+(\.\d+)?\.?$", s):
            res.append("\n### " + s)
            continue
        res.append(s)
        res.append("")
    md = "\n".join(res)
    md = re.sub(r"\n{3,}", "\n\n", md)
    open(OUT, "w", encoding="utf-8").write(md.strip() + "\n")
    print("меток:", len(marks), "| символов:", len(md))


if __name__ == "__main__":
    build()

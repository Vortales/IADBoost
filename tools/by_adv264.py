# -*- coding: utf-8 -*-
"""ACT. 264: Закон об адвокатской деятельности, ст. 7 — примечание об объёме обязанности
предоставлять сведения."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fulltext import article, build, resolve

AD = os.path.basename(resolve("Закон Об адвокатской деятельности и адвокатуре в штате San-Andreas.json"))

OUT = "Законопроекты 264 (объём сведений адвоката)"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "Законопроекты", OUT)
os.makedirs(DIR, exist_ok=True)

a7 = article(AD, "7")

NOTE = (
    "Примечание: Адвокат вправе запрашивать сведения, необходимые для оказания юридической помощи, "
    "в порядке, установленном статьей 9 настоящего Закона, и не обязан предоставлять государственным "
    "органам, их должностным лицам и иным лицам сведения, составляющие адвокатскую тайну: такие "
    "сведения раскрываются только с согласия доверителя либо в случаях, прямо предусмотренных "
    "законом. Отказ адвоката от предоставления таких сведений не является неисполнением "
    "обязанностей адвоката; обязанность предъявлять удостоверение или лицензию сохраняется."
)

A7_NEW = a7 + "\n" + NOTE

assert a7.count("на допрос.") == 1
L = "Статья 7\n" + a7.replace("на допрос.", "[[R]]на допрос.[[/R]]", 1)
R = "Статья 7\n" + a7 + "[[G]]\n" + NOTE + "[[/G]]"
rows = [(L, R)]

SECTION1 = (
    "Законопроект направлен на устранение правового пробела путем закрепления за адвокатом права "
    "запрашивать сведения, необходимые для оказания юридической помощи, и освобождения его от "
    "обязанности раскрывать сведения, составляющие адвокатскую тайну."
)

fname = "ACT.264.Закон об адвокатской деятельности (объём сведений адвоката).docx"
subtitle = "о внесении изменений в Закон «Об адвокатской деятельности и адвокатуре в штате San-Andreas»"
build([("SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Закон «Об адвокатской деятельности и адвокатуре в штате San-Andreas»", rows)],
      os.path.join(DIR, fname), "ACT. 264", subtitle, SECTION1)

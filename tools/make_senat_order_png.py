def blocks():
    out = []
    for head, items in SECTIONS:
        out.append(("h", head))
        for num, text in items:
            out.append(("p", (num, text)))
    return out


def render_block(d, y, b, draw=True):
    kind, payload = b
    if kind == "h":
        return h_block(d, y, payload, draw)
    return p_block(d, y, payload[0], payload[1], draw)


def height(d, b):
    return render_block(d, 0, b, draw=False)


def paginate(d, bs, start_y):
    pages, cur, y = [], [], start_y
    for i, b in enumerate(bs):
        h = height(d, b)
        need = h + (30 if b[0] == "h" else 0)
        if b[0] == "h" and i + 1 < len(bs):
            need += height(d, bs[i + 1]) + 10
        if cur and y + need > LIMIT:
            pages.append(cur)
            cur, y = [], TOP2
        cur.append(b)
        y += h + (30 if b[0] == "h" else 0)

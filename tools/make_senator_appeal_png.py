_cache = {}


def F(path, size):
    k = (path, size)
    if k not in _cache:
        _cache[k] = ImageFont.truetype(path, size)
    return _cache[k]


def tw(d, s, font):
    b = d.textbbox((0, 0), s, font=font)
    return b[2] - b[0]


def tracked(d, x, y, text, font, tracking, fill=INK, center=None):
    if center is not None:
        total = sum(tw(d, c, font) for c in text) + tracking * (len(text) - 1)
        x = center - total / 2
    for ch in text:
        d.text((x, y), ch, font=font, fill=fill)
        x += tw(d, ch, font) + tracking
    return x


def md_runs(text, size, base=FR, bold=FB, italic=FI, color=INK):
    """**жирный**, _курсив_ — минимальная разметка внутри абзаца."""
    out, buf, mode = [], "", None
    i = 0
    while i < len(text):
        if text.startswith("**", i):
            if buf:
                out.append((buf, _font(mode, size, base, bold, italic), color))
            buf, mode = "", ("bold" if mode != "bold" else None)
            i += 2
        elif text[i] == "_" and mode != "italic":
            if buf:
                out.append((buf, _font(mode, size, base, bold, italic), color))
            buf, mode = "", "italic"
            i += 1
        elif text[i] == "_" and mode == "italic":
            if buf:
                out.append((buf, _font(mode, size, base, bold, italic), color))
            buf, mode = "", None
            i += 1
        else:
            buf += text[i]
            i += 1
    if buf:
        out.append((buf, _font(mode, size, base, bold, italic), color))
    return out


def _font(mode, size, base, bold, italic):
    if mode == "bold":
        return F(bold, size)
    if mode == "italic":
        return F(italic, size)
    return F(base, size)



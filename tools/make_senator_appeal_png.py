def build(path):
    blocks = content()
    scratch = Image.new("RGB", (W, H), "white")
    d0 = ImageDraw.Draw(scratch)
    heights = measure(d0, blocks)

    # пагинация: заголовок не отрывается от следующего блока
    pages, cur, y = [], [], None
    for i, (b, (h, keep)) in enumerate(zip(blocks, heights)):
        top = FIRST_TOP if not pages else NEXT_TOP
        if y is None:
            y = top
        need = h
        if (keep or b[0] == "h") and i + 1 < len(blocks):
            need += heights[i + 1][0]
        if y + need > BOTTOM and cur:
            pages.append(cur)
            cur, y = [], NEXT_TOP
        cur.append((b, y, h))
        y += h
    pages.append(cur)

    total = len(pages)
    root, ext = os.path.splitext(path)
    files = []
    for i, page in enumerate(pages):
        img = Image.new("RGB", (W, H), "white")
        d = ImageDraw.Draw(img)
        page_frame(img, d)
        if i == 0:
            first_page_header(img, d)
        top = FIRST_TOP if i == 0 else NEXT_TOP
        if i:
            running_head(d, i + 1, total)
        footer(d, i + 1, total)
        yy = top
        for b, _, _ in page:
            yy = draw_block(d, img, yy, b)
        if i == total - 1:
            signature_block(d, min(max(yy + 60, 2450), 3400))
        out = f"{root} — стр. {i + 1}{ext}" if total > 1 else path
        img.save(out, "PNG", dpi=(300, 300))
        files.append(out)
    for f in files:
        print("OK", f)
    print("страниц:", total)
    return files



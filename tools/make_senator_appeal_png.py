SIZE = 37
LH = int(SIZE * 1.56)
HSIZE = 27
HLH = 44


def strip_keep(b):
    """Снимает служебный префикс KEEP и сообщает, нужно ли держать блок
    вместе со следующим."""
    idx = 2 if b[0] != "p" else 1
    if len(b) > idx and isinstance(b[idx], str) and b[idx].startswith("KEEP"):
        vals = list(b)
        vals[idx] = vals[idx][4:]
        return tuple(vals), True
    return b, False


def measure(d, blocks):
    """Возвращает список (block, height, keep)."""
    res = []
    for raw in blocks:
        b, keep = strip_keep(raw)
        kind = b[0]
        if kind == "greet":
            h = LH + 44
        elif kind == "h":
            h = 66 + HLH + 20
        elif kind == "p":
            lines = wrap(d, tokenize(md_runs(b[1], SIZE)), BW)
            h = len(lines) * LH + 26
        elif kind == "n":
            lines = wrap(d, tokenize(md_runs(b[2], SIZE)), BW - 96)
            h = len(lines) * LH + 26
        elif kind == "s":
            lines = wrap(d, tokenize(md_runs(b[2], SIZE)), BW - 170)
            h = len(lines) * LH + 18
        elif kind == "q":
            lines = wrap(d, tokenize(md_runs(b[1], SIZE - 4, italic=FI)),
                         BW - 150)
            h = len(lines) * int((SIZE - 4) * 1.5) + 46
        elif kind == "att":
            lines = wrap(d, tokenize(md_runs(b[2], SIZE - 1)), BW - 330)
            h = len(lines) * LH + 8
        elif kind == "sp":
            h = b[1]
        else:
            h = 0
        res.append((h, keep))
    return res


def draw_block(d, img, y, raw):
    b, _ = strip_keep(raw)
    kind = b[0]
    if kind == "greet":
        d.text((LEFT, y), b[1], font=F(FB, SIZE + 3), fill=INK)
        return y + LH + 44
    if kind == "h":
        y += 66
        tracked(d, LEFT, y, b[1], F(FB, HSIZE), 3.4, GREEN)
        d.line([(LEFT, y + HLH + 4), (LEFT + 92, y + HLH + 4)],
               fill=GREEN, width=4)
        return y + HLH + 20
    if kind == "p":
        lines = wrap(d, tokenize(md_runs(b[1], SIZE)), BW)
        return draw_lines(d, y, lines, LH, LEFT, BW) + 26
    if kind == "n":
        num_font = F(FB, SIZE)
        d.text((LEFT, y), b[1], font=num_font, fill=DEEP)
        runs = md_runs(b[2], SIZE)
        lines = wrap(d, tokenize(runs), BW - 96)
        return draw_lines(d, y, lines, LH, LEFT + 96, BW - 96) + 26
    if kind == "s":
        num_font = F(FB, SIZE - 2)
        d.text((LEFT + 96, y), b[1], font=num_font, fill=DEEP)
        runs = md_runs(b[2], SIZE)
        lines = wrap(d, tokenize(runs), BW - 170)
        return draw_lines(d, y, lines, LH, LEFT + 170, BW - 170) + 18
    if kind == "q":
        fs = SIZE - 4
        lh = int(fs * 1.5)
        runs = md_runs(b[1], fs, italic=FI)
        lines = wrap(d, tokenize(runs), BW - 150)
        h = len(lines) * lh + 46
        d.rectangle([LEFT + 40, y - 4, RIGHT - 40, y + h - 18], fill=PALE)
        d.rectangle([LEFT + 40, y - 4, LEFT + 46, y + h - 18], fill=GREEN)
        draw_lines(d, y + 14, lines, lh, LEFT + 88, BW - 150)
        return y + h
    if kind == "att":
        num_font = F(FB, SIZE)
        d.text((LEFT + 12, y), b[1], font=num_font, fill=DEEP)
        runs = md_runs(b[2], SIZE - 1)
        lines = wrap(d, tokenize(runs), BW - 330)
        yy = draw_lines(d, y, lines, LH, LEFT + 70, BW - 330)
        d.text((RIGHT - tw(d, b[3], F(FI, SIZE - 4)), y), b[3],
               font=F(FI, SIZE - 4), fill=GREY)
        return yy + 8
    if kind == "sp":
        return y + b[1]
    return y



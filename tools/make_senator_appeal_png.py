def tokenize(runs):
    toks = []
    for text, font, col in runs:
        parts = text.split(" ")
        for i, p in enumerate(parts):
            if p:
                toks.append((p, font, col))
            if i < len(parts) - 1:
                toks.append((None, font, col))
    return toks


def tkw(d, t):
    return tw(d, " ", t[1]) if t[0] is None else tw(d, t[0], t[1])


def wrap(d, toks, width, first_indent=0):
    lines, cur = [], []
    for t in toks:
        if t[0] is None:
            if cur:
                cur.append(t)
            continue
        limit = width - (first_indent if not lines else 0)
        if sum(tkw(d, x) for x in cur + [t]) <= limit or not cur:
            cur.append(t)
        else:
            while cur and cur[-1][0] is None:
                cur.pop()
            lines.append(cur)
            cur = [t]
    while cur and cur[-1][0] is None:
        cur.pop()
    if cur:
        lines.append(cur)
    return lines


def draw_lines(d, y, lines, lh, left, width, first_indent=0, justify=True):
    for i, ln in enumerate(lines):
        last = i == len(lines) - 1
        x = left + (first_indent if i == 0 else 0)
        limit = width - (first_indent if i == 0 else 0)
        gaps = sum(1 for t in ln if t[0] is None)
        natural = sum(tkw(d, t) for t in ln)
        extra = (limit - natural) / gaps if (gaps and justify and not last) else 0
        for tok, font, col in ln:
            if tok is None:
                x += tw(d, " ", font) + extra
            else:
                d.text((x, y), tok, font=font, fill=col)
                x += tw(d, tok, font)
        y += lh
    return y



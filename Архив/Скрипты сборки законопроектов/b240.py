# -*- coding: utf-8 -*-
from pack import sec, pair, bill, OUT
from make_acts import build

PK = "Процессуальный кодекс штата Сан-Андреас.json"
lines = sec(PK, 31).split("\n")
def L(needle):
    r = [l for l in lines if needle in l]
    assert len(r) == 1, (needle, len(r))
    return r[0]

r1 = pair(L("д) Руководство задержанного"),
          "д) Руководство задержанного сотрудника государственных органов в соответствии со ст. 19 ч 1 настоящего Кодекса;",
          "д) Один представитель руководства задержанного сотрудника государственных органов в соответствии со ст. 19 ч. 1 настоящего Кодекса;")

r2 = pair(L("ж) Один сотрудник IB"),
          "ж) Один сотрудник IB для проведения надзора;",
          "ж) Один сотрудник Intelligence Branch (IB) Федерального Расследовательского Бюро для проведения надзора;")

r3 = pair(L("Detective Bureau"),
          "Detective Bureau (Los Santos Police Department, Los Santos County Sheriff Department) и Criminal Investigation Department (Federal Investigation Bureau)",
          "Detective Bureau (далее — DB) (Los Santos Police Department, Los Santos County Sheriff Department) и Criminal Investigation Department (далее — CID) (Federal Investigation Bureau)")

r4 = pair(L("не допускается замена субъектов"),
          "указанных в пункте (В) настоящей статьи",
          "указанных в части 1 настоящей статьи")

r5 = pair(L("л) один уполномоченный"), "л) один уполномоченный", "л) Один уполномоченный")

b = bill(240,
 "ACT. 240 — Уточнение статьи 18 Процессуального кодекса.docx",
 "о внесении изменений в статью 18 Процессуального кодекса штата San-Andreas",
 "Статья 18 Процессуального кодекса устанавливает исчерпывающий перечень субъектов задержания, однако использует сокращения «IB», «DB» и «CID», которые в Кодексе не раскрыты, а в пункте «д» допускает участие неограниченного числа представителей руководства задержанного, тогда как примечание к части 4 той же статьи допускает лишь одного представителя. Кроме того, примечание к части 4 ссылается на «пункт (В)» — с заглавной буквы и в скобках, что не соответствует буквенной нумерации части 1. Законопроект: (1) приводит пункт «д» в соответствие с примечанием — «один представитель руководства»; (2) раскрывает сокращения IB (Intelligence Branch), DB (Detective Bureau) и CID (Criminal Investigation Department) при первом упоминании; (3) заменяет ссылку на «пункт (В)» ссылкой на часть 1 статьи; (4) устраняет разнобой в регистре буквы «л». Объём полномочий субъектов задержания не изменяется: пункт «д» уже ограничен примечанием, а сокращения лишь получают расшифровку.",
 "SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Процессуальный кодекс штата San-Andreas",
 [r1, r2, r3, r4, r5])
build(b, OUT)

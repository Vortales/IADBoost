# -*- coding: utf-8 -*-
from pack import sec, bill, OUT
from make_acts import build

AK = "Административный кодекс штата San-Andreas.json"
head = sec(AK, 67).strip()          # "Статья 11."
body = sec(AK, 68).strip()          # "1 Оскорбление\nч. 1 ..."
lines = body.split("\n")
assert lines[0].startswith("1 "), lines[0]
rest = "\n".join(lines[1:])
left  = "[[R]]Статья 11.[[/R]]\n[[R]]1[[/R]] " + lines[0][2:] + "\n" + rest
right = "[[G]]Статья 11.1[[/G]]\n" + lines[0][2:] + "\n" + rest

b = bill(241,
 "ACT. 241 — Восстановление нумерации статей 11.1 и 11.2 Административного кодекса.docx",
 "о внесении технического исправления в Административный кодекс штата San-Andreas",
 "В Главе XI Административного кодекса штата San-Andreas нарушена нумерация статей. Первая статья главы оформлена как «Статья 11.» — без номера и без названия, а следующий за ней фрагмент начинается со строки «1 Оскорбление» и не имеет заголовка статьи. Следующая статья при этом пронумерована как «Статья 11.2 Клевета». В результате статья 11.1 в Кодексе отсутствует, статья 11 не имеет содержания, а статья 11.2 не имеет предшествующей статьи с номером 11.1. Законопроект объединяет заголовок и текст и присваивает статье номер 11.1; нумерация статей 11.1 и 11.2 становится последовательной. Содержание нормы и санкция не изменяются.",
 "SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Административный кодекс штата San-Andreas",
 [(left, right)])
build(b, OUT)

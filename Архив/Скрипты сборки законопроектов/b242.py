# -*- coding: utf-8 -*-
from pack import sec, pair, bill, OUT
from make_acts import build

TK = "Трудовой кодекс штата San-Andreas.json"
def head(n):
    return sec(TK, n).split("\n")[0].strip()

pairs = [
    (head(19), "Глава III", "Глава IV"),
    (head(28), "Глава IV", "Глава V"),
    (head(35), "Глава V", "Глава VI"),
    (head(38), "Глава VI", "Глава VII"),
]
rows = [pair(t, o, nw) for t, o, nw in pairs]

b = bill(242,
 "ACT. 242 — Перенумерация глав Трудового кодекса.docx",
 "о внесении технического исправления в Трудовой кодекс штата San-Andreas",
 "В Трудовом кодексе штата San-Andreas глава, регулирующая трудовой договор, обозначена как «Глава III», тогда как глава, регулирующая основные права и обязанности сторон трудовых отношений, уже имеет номер III. В результате в Кодексе две главы III, а главы IV, V и VI следуют за ними со сдвигом. Законопроект присваивает главе о трудовом договоре номер IV и последовательно перенумеровывает главы о рабочем времени, оплате труда и дисциплине труда в V, VI и VII. Ссылок на номера этих глав в иных актах законодательства штата не имеется, поэтому изменения носят исключительно редакционный характер и содержание норм не затрагивают.",
 "SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Трудовой кодекс штата San-Andreas",
 rows)
build(b, OUT)

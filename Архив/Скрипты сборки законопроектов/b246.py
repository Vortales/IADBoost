# -*- coding: utf-8 -*-
from pack import sec, pair, bill, OUT
from make_acts import build

F = "Закон “О деятельности региональных правоохранительных органах штата Сан-Андреас”.json"

line = [l for l in sec(F, 8).split("\n") if "сотрудники сотрудники" in l][0]
r1 = pair(line, "сотрудники сотрудники", "сотрудники")

old6 = ("Статья 6.\nНарушение юрисдикции без оснований предусмотренных настоящим законом, наказуемо "
        "административным штрафом в размере 20.000$, который может быть назначен служащими Офиса "
        "генерального прокурора или судом, а также органами, осуществляющими административный надзор "
        "внутри структуры, служащим которой является правонарушитель.")
new6 = ("Статья 6.\nНарушение юрисдикции без оснований, предусмотренных настоящим законом, влечёт "
        "административную ответственность, предусмотренную статьёй 9.5 Административного кодекса "
        "штата San-Andreas.")
r2 = ("[[R]]Статья 6.[[/R]]\n[[R]]" + old6.split("\n",1)[1] + "[[/R]]",
      "[[G]]Статья 6.[[/G]]\n[[G]]" + new6.split("\n",1)[1] + "[[/G]]")

b = bill(246,
 "ACT. 246 — Технические исправления в Закон о региональных правоохранительных органах.docx",
 "о внесении изменений в Закон «О деятельности региональных правоохранительных органах штата Сан-Андреас»",
 "В Закон «О деятельности региональных правоохранительных органах штата Сан-Андреас» вносятся два изменения. (1) В пункте «б» части 3 статьи 5 допущен повтор слова — «сотрудники сотрудники оперативно-следственных подразделений»; повтор устраняется. (2) Статья 6 устанавливает за нарушение юрисдикции административный штраф в размере 20.000$, однако тот же состав и та же санкция уже предусмотрены статьёй 9.5 Административного кодекса штата San-Andreas. Две параллельные нормы создают неопределённость в вопросе о том, какой процедурой — законом или Кодексом — оформляется привлечение к ответственности, и допускают повторное наказание за одно деяние. Законопроект превращает статью 6 в отсылочную норму: состав правонарушения остаётся в законе, а порядок и санкция применяются по Административному кодексу.",
 "SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Закон «О деятельности региональных правоохранительных органах штата Сан-Андреас»",
 [r1, r2])
build(b, OUT)

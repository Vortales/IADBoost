# -*- coding: utf-8 -*-
from pack import sec, pair, bill, OUT
from make_acts import build

F = "Приложение №1 к Уголовному кодексу штата Сан-Андреас О закрытых, охраняемых и особо охраня….json"
def L(n, needle):
    r = [l for l in sec(F, n).split("\n") if needle in l]
    assert len(r) == 1, (needle, len(r))
    return r[0]

r1 = pair("Статья 6. Визуализация.\n" + L(9, "Желтымцветом"),
          "Желтымцветом выделяются", "Желтым цветом выделяются")
r2 = pair(L(9, "Краснымцветом"), "Краснымцветом выделяются", "Красным цветом выделяются")
r3 = pair(L(9, "цель законную цель"),
          "имеющим цель законную цель визита", "имеющим законную цель визита")
r4 = pair(L(7, "руководство руководство"),
          "одно руководство руководство сотрудников государственных органов в случае задержания их подчиненных",
          "один представитель руководства сотрудников государственных органов в случае задержания их подчиненных")

b = bill(247,
 "ACT. 247 — Технические исправления в Приложение № 1 к Уголовному кодексу.docx",
 "о внесении технических исправлений в Приложение № 1 к Уголовному кодексу штата San-Andreas",
 "В Приложении № 1 к Уголовному кодексу штата San-Andreas «О закрытых, охраняемых и особо охраняемых территориях штата San-Andreas» допущены технические ошибки: (1) в статье 6 слова «Желтымцветом» и «Краснымцветом» написаны слитно; (2) в той же статье допущен повтор — «имеющим цель законную цель визита»; (3) в статье 4 в перечне лиц, имеющих доступ на Форт Занкудо, дважды употреблено слово «руководство» — «одно руководство руководство сотрудников государственных органов». Законопроект устраняет слитные написания, повтор слова «цель» и повтор слова «руководство», заменяя последний на «один представитель руководства». Режим доступа на объекты не изменяется.",
 "SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Приложение № 1 к Уголовному кодексу штата San-Andreas",
 [r1, r2, r3, r4])
build(b, OUT)

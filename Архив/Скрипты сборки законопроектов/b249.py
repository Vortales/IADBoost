# -*- coding: utf-8 -*-
from pack import sec, pair, bill, OUT
from make_acts import build

F = "Закон «О системе ордеров штата Сан-Андреас».json"
def L(n, needle):
    r = [l for l in sec(F, n).split("\n") if needle in l]
    assert len(r) == 1, (needle, len(r))
    return r[0]

r1 = pair(L(9, "рейдового мероприятия"), "провести рейдового мероприятия", "провести рейдовое мероприятие")

r2 = pair(L(9, "LSSD"),
          "в) Орган, предусмотренный для его выполнения: FIB, LSSD, LSPD, SANG, USSS.",
          "в) Органы, предусмотренные для его исполнения: FIB, LSCSD, LSPD, SANG, USSS.")

r3 = pair(L(11, "может быть отозвано"),
          "может быть отозвано лицом, его авторизовавшим",
          "может быть отозван лицом, его авторизовавшим")

r4 = pair(L(10, "Генеральным Прокурором, Губернатором или Верховным судом"),
          "требуется ордер Access to Investigation (AI), выданный Генеральным Прокурором, Губернатором или Верховным судом;",
          "требуется ордер Access to Investigation (AI), выданный Сенатом штата Сан-Андреас или комитетом Сената по этике, а также Генеральным Прокурором, Губернатором или Верховным судом;")

b = bill(249,
 "ACT. 249 — Устранение противоречий в Законе о системе ордеров.docx",
 "о внесении изменений в Закон «О системе ордеров штата San-Andreas»",
 "В Закон «О системе ордеров штата San-Andreas» вносятся исправления четырёх видов. (1) В пункте «а» части 1 статьи 6 нарушено согласование: «предписывает провести рейдового мероприятия»; правильная форма — «рейдовое мероприятие». (2) В пункте «в» части 7 статьи 6 органом, исполняющим ордер о чрезвычайном положении, назван «LSSD» — такого органа в законодательстве штата нет, используется сокращение LSCSD (Los Santos County Sheriff Department); там же единственное число «Орган» заменяется на «Органы». (3) В части 3 статьи 8 сказуемое не согласовано с подлежащим: ордер — «может быть отозвано»; правильная форма — «может быть отозван». (4) Коллизия: пункт «б» части 5 статьи 6 относит выдачу ордера AI в отношении сенаторов к компетенции Сената и комитета Сената по этике, а пункт «е» части 1 статьи 7 для спикера Сената называет только Генерального Прокурора, Губернатора и Верховный суд. Законопроект дополняет пункт «е» полномочием Сената и комитета Сената по этике, устраняя противоречие. Порядок выдачи ордеров в остальной части не изменяется.",
 "SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Закон «О системе ордеров штата San-Andreas»",
 [r1, r2, r3, r4])
build(b, OUT)

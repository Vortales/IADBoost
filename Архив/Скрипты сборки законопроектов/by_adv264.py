# -*- coding: utf-8 -*-
"""ACT. 264: Закон об адвокатской деятельности, ст. 4 ч. 2 п. «а» — примечание об объёме
сведений, которые предоставляются адвокату."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fulltext import article, build, resolve

AD = os.path.basename(resolve("Закон Об адвокатской деятельности и адвокатуре в штате San-Andreas.json"))

OUT = "Законопроекты 264 (объём сведений адвоката)"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "Законопроекты", OUT)
os.makedirs(DIR, exist_ok=True)

LOC = "Статья 4, ч. 2, пункт «а»"
p_a = [l for l in article(AD, "4").split("\n")
       if l.startswith("а) собирать сведения, необходимые для оказания юридической помощи")][0]

NOTE = (
    "Примечание: Сведения, предусмотренные пунктами «а» и «и» части 2 настоящей статьи, "
    "предоставляются адвокату в объёме, необходимом для оказания юридической помощи по конкретному "
    "поручению доверителя; в запросе указываются поручение и его предмет. "
    "Сведения, составляющие государственную тайну, и сведения о частной жизни лиц, не являющихся "
    "участниками поручения, адвокату не предоставляются."
)

assert p_a.count("их копии;") == 1
L = LOC + "\n" + p_a.replace("их копии;", "[[R]]их копии;[[/R]]", 1)
R = LOC + "\n" + p_a + "[[G]]\n" + NOTE + "[[/G]]"
rows = [(L, R)]

SECTION1 = (
    "Законопроект направлен на устранение правового пробела путем определения объёма сведений, "
    "предоставляемых адвокату по его запросу, и перечня сведений, которые ему не предоставляются."
)

fname = "ACT.264.Закон об адвокатской деятельности (объём сведений адвоката).docx"
subtitle = "о внесении изменений в Закон «Об адвокатской деятельности и адвокатуре в штате San-Andreas»"
build([("SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Закон «Об адвокатской деятельности и адвокатуре в штате San-Andreas»", rows)],
      os.path.join(DIR, fname), "ACT. 264", subtitle, SECTION1)

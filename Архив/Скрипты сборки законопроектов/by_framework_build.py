# ======================= 249. ПК — РАМОЧНАЯ РЕДАКЦИЯ =======================
ZH1 = """ж.1) Один сотрудник подразделения внутренних расследований (Internal Affairs Division, далее — IAD) — при задержании сотрудника департамента, в котором он состоит.
Полномочия сотрудника IAD, порядок осуществления внутреннего надзора и условия его участия в процессуальных действиях определяются законом «О деятельности региональных правоохранительных органов штата San-Andreas» и внутренними регламентами департамента."""


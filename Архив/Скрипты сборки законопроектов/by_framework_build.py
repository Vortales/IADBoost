A281 = """ч. 1 Подразделение внутренних расследований (Internal Affairs Division, далее — IAD) является структурным подразделением регионального правоохранительного органа, осуществляющим внутренний контроль за соблюдением сотрудниками этого органа законодательства штата San-Andreas, устава и внутренних регламентов органа.
ч. 2 Структура, штатная численность, порядок деятельности и полномочия IAD определяются руководителем регионального правоохранительного органа в соответствии с уставом органа и принимаемыми на его основе внутренними регламентами.
ч. 3 IAD вправе составлять протоколы о нарушениях юрисдикции, совершённых сотрудниками органа.
ч. 4 Сотрудник IAD является субъектом задержания в случаях, предусмотренных Процессуальным кодексом штата San-Andreas.
ч. 5 Внутренний контроль осуществляется IAD исключительно в отношении сотрудников собственного органа. IAD не вправе осуществлять контроль за деятельностью иных государственных органов."""


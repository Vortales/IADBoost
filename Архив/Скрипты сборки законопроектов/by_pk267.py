# -*- coding: utf-8 -*-
"""ACT. 267: ПК ст. 27 ч. 1 п. «д» — срок КПЗ; ст. 19 ч. 5 — исключения из вызова прокурора."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fulltext import article, build, resolve
from by_act import row, line

PK = os.path.basename(resolve("Процессуальный кодекс штата Сан-Андреас.json"))

OUT = "Законопроекты 266–269 (устранение коллизий)"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, "Законопроекты", OUT)
os.makedirs(DIR, exist_ok=True)

# --- ст. 27 ч. 1 п. «д» ---
a27 = article(PK, "27")
d_old = line(a27, "д) Поместить его в КПЗ")
assert d_old.count("на срок, установленный уголовным кодексом") == 1
d_left = d_old.replace("на срок, установленный уголовным кодексом",
                       "на срок, [[R]]установленный уголовным кодексом[[/R]]", 1)
d_right = d_old.replace(
    "на срок, установленный уголовным кодексом",
    "на срок [[G]]из расчета 10 минут за каждый уровень боло-розыска, но не более 50 минут, "
    "если иное не установлено уголовным кодексом или решением суда[[/G]]", 1)

# --- ст. 19 ч. 5 (новая часть) ---
a19 = article(PK, "19")
assert a19.rstrip().endswith("вызов прокурора так же является обязательным.")
p5 = ("Требования частей 1–4 настоящей статьи не применяются при задержании сотрудника "
      "государственной организации по решению суда, на основании ордера, в период "
      "государственного переворота, а также в случае отсутствия у задерживаемого удостоверения, "
      "жетона, бейджика или иных элементов одежды, идентифицирующих его как государственного служащего.")

rows = [
    row("Статья 19, ч. 5", None, "ч. 5. " + p5),
    ("Статья 27, ч. 1, пункт «д»\n" + d_left, "Статья 27, ч. 1, пункт «д»\n" + d_right),
]

SECTION1 = (
    "Законопроект направлен на устранение правовой коллизии путем установления предельного срока "
    "содержания в КПЗ и оснований, при которых задержание сотрудника государственной организации "
    "не требует вызова прокурора."
)

fname = "ACT.267.Процессуальный кодекс (срок КПЗ и задержание госслужащих).docx"
subtitle = "о внесении изменений в Процессуальный кодекс штата San-Andreas"
build([("SECTION. 2. ВНЕСЕНИЕ ПРАВКИ В Процессуальный кодекс штата San-Andreas", rows)],
      os.path.join(DIR, fname), "ACT. 267", subtitle, SECTION1)

# -*- coding: utf-8 -*-
"""ACT. 304-307: четыре отдельных проекта о защите задержанного.

Каждый проект исходит из действующего локального среза и не предполагает
принятия других проектов. Номера и дата внесения не подтверждены.
"""
import argparse
from dataclasses import dataclass
from pathlib import Path
import re

import billkit
from build_act303 import bold, plain, polish_pagination
from build_sang_299_300 import clear_attest
from legal_sources import AD, AD_TITLE, PC, PC_TITLE, clean, excerpt
from make_acts import build

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Законопроекты"
PC_GEN = "Процессуального кодекса штата Сан-Андреас"
TOKEN = re.compile(r"\[\[/?(?:R|G|B)\]\]")


@dataclass(frozen=True)
class Patch:
    number: int
    source: str
    section: int
    locator: str
    old: str
    new: str
    marker: str = ""


def specs():
    documents = {name: billkit.load(name) for name in (PC, AD)}
    titles = {PC: PC_TITLE, AD: AD_TITLE}
    collections = {n: [] for n in range(304, 308)}
    patches = []
    spans = {}

    def replace(number, source, section, locator, old, new):
        text, old = clean(documents[source][section]), clean(old)
        if not old or text.count(old) != 1:
            raise ValueError(f"Не найден или не уникален фрагмент {number}, {locator}")
        i, j = text.index(old), text.index(old) + len(old)
        for a, b, where in spans.setdefault((source, section), []):
            if i < b and a < j:
                raise ValueError(f"Пересечение правок: {where}, {number}: {locator}")
        spans[(source, section)].append((i, j, f"{number}: {locator}"))
        head = f"{bold(titles[source])}\n{locator}\n"
        collections[number].append((head + "[[R]]" + old + "[[/R]]",
                                    head + "[[G]]" + new + "[[/G]]"))
        patches.append(Patch(number, source, section, locator, old, plain(new)))

    def add(number, source, section, locator, absent, new):
        if absent in clean(documents[source][section]):
            raise ValueError(f"Норма уже существует: {number}, {locator}")
        head = f"{bold(titles[source])}\n{locator}\n"
        collections[number].append((head + "В действующей редакции отсутствует.",
                                    head + "[[G]]" + new + "[[/G]]"))
        patches.append(Patch(number, source, section, locator, "", plain(new), absent))

    add(304, PC, 36, "Статья 23, часть 2", "\nч. 2.",
        "ч. 2. Если участвующий в задержании адвокат после ознакомления с материалами указал факты и конкретное основание освобождения по части 1 статьи 20 настоящего Кодекса, а сотрудник, проводящий задержание, не согласен, он по устному ходатайству адвоката в КПЗ или допросной вызывает туда прокурора.\n"
        "Если прокурор уже участвует или вызван по статье 19, доводы сообщаются ему при первой возможности. Повторный вызов по тем же обстоятельствам не производится; при новых существенных обстоятельствах ходатайство рассматривается вновь.\n"
        "Прокурор незамедлительно оценивает доводы в пределах полномочий. Если прокурор, вызванный по настоящей части, не ответил или не прибыл в течение 10 минут с момента вызова, производство продолжается только при наличии законных оснований. Порядок и сроки статьи 19 сохраняются. При наличии основания лицо освобождается незамедлительно, не дожидаясь прокурора. Право на обжалование сохраняется.")
    add(304, PC, 33, "Статья 20, часть 2, пункт «ж»", "\nж)",
        "ж) при ожидании ответа или прибытия прокурора по части 2 статьи 23 настоящего Кодекса - на фактическое время ожидания, но не более 10 минут с момента вызова. Одновременно протекающие периоды приостановления не суммируются; порядок приостановления по статье 19 настоящего Кодекса сохраняется.")
    replace(304, AD, 13, "Статья 5.1, часть 2",
        "ч. 2. Заключение не обладает юридической силой и не влечет за собой наступления каких-либо правовых последствий для участников процесса.",
        "ч. 2. Заключение не обязательно для сотрудника и само по себе не является решением об освобождении или признанием вины. В случаях и порядке, предусмотренных "
        + bold("Процессуальным кодексом штата Сан-Андреас") + ", адвокат вправе заявить ходатайство о вызове прокурора.")

    old_g = excerpt(documents[PC][36], "г) В случае задержания лица по автоматически созданной записи")
    replace(305, PC, 36, "Статья 23, часть 1, пункт «г» и исключение", old_g,
        "г) По заявлению задержанного или участвующего в задержании адвоката приобщить к материалам дела представленные ими доказательства и иные материалы, которые относятся к событию и, по их утверждению, свидетельствуют в пользу задержанного, независимо от основания задержания. Представленные аудио- и видеозаписи изучаются во время задержания; лица, представившие записи, выбирают относящиеся к событию фрагменты общей продолжительностью до 10 минут за задержание. Материалы оцениваются по статьям 11-14 настоящего Кодекса. Их представление само по себе не отменяет ордер или судебное решение.\n"
        "Если запись хранится на удаленном сервере и не может быть представлена незамедлительно, ее предоставление может занимать до 1 часа; ожидание само по себе не приостанавливает и не продлевает срок задержания. Невозможность немедленно представить запись не лишает права представить ее позднее или обжаловать решение.")
    old_e = excerpt(documents[PC][33], "е) при просмотре видеофиксации")
    replace(305, PC, 33, "Статья 20, часть 2, пункт «е»", old_e,
        "е) при изучении представленных задержанным или его адвокатом аудио- и видеозаписей в порядке пункта «г» части 1 статьи 23 настоящего Кодекса - на фактическое время изучения, но не более 10 минут в совокупности за задержание. Одновременно протекающие периоды приостановления не суммируются; иные самостоятельные основания приостановления сохраняются.")

    add(306, PC, 67, "Статья 43, часть 3", "\nч. 3.",
        "ч. 3. Во время задержания сотрудник, проводящий задержание, непосредственно после заявления рассматривает устное ходатайство задержанного или участвующего адвоката по вопросам задержания и до решения о наказании устно сообщает об удовлетворении либо о полном или частичном отказе с указанием причин. При повторном ходатайстве по тем же обстоятельствам сотрудник вправе сослаться на ранее сообщенные причины.\n"
        "Если решение не входит в полномочия сотрудника, он сообщает об этом и порядке обращения к уполномоченному лицу; при участии такого лица передает ходатайство ему. Ходатайство и ответ фиксируются в видеозаписи по статье 32 настоящего Кодекса. Немотивированный отказ или нерассмотрение ходатайства являются нарушением процессуального порядка. Если нарушение не устранено до решения о наказании, уполномоченный прокурор или суд при рассмотрении жалобы признает последующий арест незаконным в пределах своих полномочий.")

    add(307, PC, 36, "Статья 23, часть 1, пункт «д»", "\nд)",
        "д) По вопросам участвующего в задержании адвоката сообщать известные сотруднику фактические обстоятельства, относящиеся к событию и задержанию, включая время, место и способ фиксации события, а также последовательность применения силы и отдававшиеся команды. При отсутствии сведений сообщается об этом. Сведения с ограниченным доступом предоставляются в установленном законом порядке. Настоящий пункт не обязывает разъяснять адвокату правовую оценку или состав правонарушения и не отменяет обязанностей по пунктам «б» и «в» настоящей части. Обязанность разъяснить квалификацию задержанному сохраняется.")

    config = (
        (304, "Законопроекты 304 - прокурор по ходатайству адвоката", "ACT.304.Процессуальный кодекс и Закон об адвокатуре.docx",
         (PC_TITLE, AD_TITLE), "Законопроект устанавливает вызов прокурора при мотивированном споре об освобождении."),
        (305, "Законопроекты 305 - материалы защиты", "ACT.305.Процессуальный кодекс.docx",
         (PC_TITLE,), "Законопроект устанавливает порядок изучения аудио- и видеоматериалов защиты."),
        (306, "Законопроекты 306 - устные ходатайства", "ACT.306.Процессуальный кодекс.docx",
         (PC_TITLE,), "Законопроект устанавливает порядок рассмотрения устных ходатайств при задержании."),
        (307, "Законопроекты 307 - фактические обстоятельства", "ACT.307.Процессуальный кодекс.docx",
         (PC_TITLE,), "Законопроект уточняет предоставление адвокату сведений о фактических обстоятельствах."),
    )
    bills = []
    for num, folder, file, act_titles, summary in config:
        subtitle = "о внесении изменений в " + " и ".join(bold(x) for x in act_titles)
        section2 = "SECTION. 2. ВНЕСЕНИЕ ПРАВОК В ЗАКОНОДАТЕЛЬСТВО ШТАТА"
        bill = billkit.bill(num, "", file, subtitle, summary, section2, collections[num])
        bill["clear_template_metadata"] = True
        # Крупная строка с левой редакцией свободно переходит на следующую страницу.
        bill["table_font_size"] = 11.5
        bill["keep_rows_together"] = tuple(plain(l).split("\n", 2)[1] for l, r in collections[num]
                                          if max(len(plain(l)), len(plain(r))) < 1300)
        bills.append((folder, bill))
    return bills, patches, documents


def main(only=None):
    bills, _, _ = specs()
    if only is not None and only not in {b["num"] for _, b in bills}:
        raise ValueError(f"Нет проекта ACT. {only}")
    for folder, bill in bills:
        if only is not None and bill["num"] != only:
            continue
        outdir = OUT / folder
        outdir.mkdir(parents=True, exist_ok=True)
        build(bill, str(outdir))
        path = outdir / bill["file"]
        clear_attest(path)
        polish_pagination(path)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", type=int, choices=range(304, 308), metavar="НОМЕР")
    main(parser.parse_args().only)
